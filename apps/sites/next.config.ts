import type { NextConfig } from 'next';
import { SECURITY_HEADERS } from './lib/security-headers';

const config: NextConfig = {
  // A separate output folder for local acceptance builds (tests/e2e/scripts/acceptance.ts --prod), so a production
  // build never shares a cache with the development server (that mix made pages reload in a loop, P2 S10).
  ...(process.env.NEXT_DIST_DIR ? { distDir: process.env.NEXT_DIST_DIR } : {}),
  reactStrictMode: true,
  poweredByHeader: false,
  transpilePackages: ['@platform/ui', '@platform/schema', '@platform/blocks'],
  async headers() {
    // SEC-03 baseline on every path; the host pages add a strict per-response CSP (lib/pages.ts).
    return [
      { source: '/:path*', headers: [...SECURITY_HEADERS] },
      // Self-hosted fonts (public/fonts, generated by scripts/copy-fonts.mjs). File names carry no content hash, so the
      // cache is long but not immutable: a font package upgrade reaches visitors within 30 days at the latest.
      {
        source: '/fonts/:file*',
        headers: [{ key: 'Cache-Control', value: 'public, max-age=2592000, stale-while-revalidate=86400' }],
      },
      // Preview links (FR-TPL-09) carry their token in the path: nothing they link to may see it in a Referer. A
      // later rule wins over the baseline's Referrer-Policy.
      { source: '/p/:path*', headers: [{ key: 'Referrer-Policy', value: 'no-referrer' }] },
    ];
  },
};

export default config;
