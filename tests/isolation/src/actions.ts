/**
 * Server-action registry for the IDOR harness (SEC-10: "IDOR tests for every resource type"; P1 S5 onwards).
 *
 * Every exported function in a `'use server'` module of apps/dashboard must appear here, either with the
 * selectors it takes from the browser (each one probed by `actions.test.ts`) or with the reason it has none.
 * `actions.test.ts` fails CI when an action is missing, so a new action cannot ship unprobed.
 *
 * The probes call the service method each action wraps: an action only adds the session lookup (user id from
 * the server) and form parsing, so the service is where a browser-supplied id meets authorization.
 */

